def government_at(date: str) -> dict | None:
    """그날(YYYY-MM-DD) 임기였던 정부. 파면일은 다음 구간(권한대행)으로 센다 — 그날 효력이 났다."""
    hit = None
    for g in GOVERNMENTS:
        if g["start"] <= date and (g["end"] is None or date <= g["end"]):
            hit = g
    return hit
