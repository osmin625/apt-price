"""중개사 메모에서 키워드를 뽑는다.

## 왜 원문을 그대로 두지 않나

메모는 한 줄에 다 붙어 있고 띄어쓰기가 제각각이다. 실제로 받은 것들:

    "세끼고 피3000 확정가500할인됨 2in0ne 냉장고"
    "올수리. 전세 안고. 투자가치 상승중. 전망 굿. 매탄권선역 인접동"
    "급매0탁트인전망완전굿 탑층 시에2대 정상입주 내집마련기회"

순위표에 이걸 그대로 흘리면 칸이 터지고, 50건을 눈으로 훑어야 '세 끼고 나온 것'을
고를 수 있다. 같은 뜻이 `세끼고`·`세안고`·`전세 안고`·`전세 끼고` 로 제각각 적히므로
검색도 안 된다. 그래서 **같은 뜻을 한 이름으로 묶는다.**

## 사전은 실제 메모 50건을 재서 만들었다

추측으로 적지 않았다. 이 세션에서 실제로 붙여넣은 목록에서 메모 50건(중복 제거)을
뽑아 규칙마다 적중률을 쟀다. 18개 규칙이 **전부** 한 번 이상 걸렸고, 50건 중 48건이
태그를 하나 이상 받았다(못 받은 둘은 "맘에 쏙드는 집, 신혼부부추천" 과
"임대놓기좋은 원룸.깔끔.주차장.엘레베이터" — 가격에 걸리는 말이 없다).

재면서 잡은 오탐 둘:

- `협의\s*가` 로 '가격 협의' 를 잡으려 했더니 **'입주협의가'** 가 걸렸다. 입주
  날짜 얘기지 가격 얘기가 아니다. 부정형 전방탐색으로 뗐고, 대신 '할인' 을 더해
  "확정가500할인됨" 을 얻었다.
- `에\s*2` 로 '에어컨 2대'(`시에2대`·`에2`)를 잡으면 **'전세 2억에 2억9천'** 같은
  금액 표현이 걸린다. 숫자 뒤에 억/만/천/% 가 오면 뺀다.

사전을 고칠 일이 생기면 `scripts/memo_report.py` 로 **실제 메모에 다시 재 보고**
고친다. 눈으로 보고 늘리지 말 것.

## 태그는 사실이 아니라 **중개사의 말**이다

'올수리' 는 우리가 확인한 것이 아니라 올린 사람이 그렇게 적었다는 뜻이다. 화면에서
사용자가 직접 쓴 비고와 구분되게 보여 주고, 원문을 호버로 같이 띄운다. 이 저장소의
"추정을 사실처럼 보여 주지 않는다" 가 그대로 적용된다.
"""

from __future__ import annotations

import re

# (이름, 패턴, 가격에 걸리는 정도). 순서가 곧 **표시 우선순위**다 — 비고 칸이
# 좁아 앞의 몇 개만 배지로 나가므로, 가격 판단에 쓰이는 것이 앞에 와야 한다.
# 괄호 안은 실제 메모 50건 중 적중 건수다(2026-10 측정).
RULES: list[tuple[str, str]] = [
    ("급매", r"급매|급급매"),                                           # 1
    ("세안고", r"세\s*(?:끼고|안고)|전세\s*(?:끼고|안고|낀)|임차인.{0,6}거주|세입자"),  # 11
    ("분양권P", r"(?:^|[^A-Za-z가-힣])[Pp]\s*\d{3,5}|피\s*\d{3,5}|프리미엄"),  # 5
    ("조정가능", r"조정\s*가능|조정\s*가(?!능)|가격\s*협의|할인"),         # 3
    ("즉시입주", r"즉시?\s*입주|정상입주|빠른\s*입주|입주\s*가능|실입주\s*가능"),  # 14
    ("입주협의", r"입주\s*일?\s*협의|날짜\s*협의|늦은\s*입주|\d{1,2}월.{0,6}입주"),  # 11
    ("올수리", r"올\s*수리|리모델링|올화이트|풀\s*수리|일부\s*수리"),       # 9
    ("조합원", r"조합원"),                                              # 2
    ("재건축", r"재건축|재개발"),                                        # 1
    ("투자", r"투자\s*가치|투자\s*영순위|투자용|수익율|수익률"),            # 5
    ("로얄층", r"로얄층|로열층|RR|탑층"),                                # 3
    ("확장", r"거실\s*확장|방\s*확장|방확|확장"),                       # 3
    ("풀옵션", r"풀\s*옵션|빌트인|옵션\s*많"),                          # 4
    ("전망", r"뻥뷰|탁\s*트인|확\s*트인|트인\s*전망|시티뷰|스카이뷰|단지뷰|초록뷰|전망|뷰"),  # 16
    ("채광", r"채광|햇살|일조"),                                        # 5
    # '에 2억' 같은 금액 표현을 피하려고 숫자 뒤를 본다. 측정으로 잡은 오탐이다.
    ("시스템에어컨", r"에어컨|시스템\s*에어컨|시\s*에(?=\s*중문|\s*$|[,.])|에\s*\d(?!\s*[억만천%년월일])"),  # 22
    ("역세권", r"역세권|역\s*인접|역\s*가까"),                          # 3
    ("학세권", r"학세권|학군"),                                         # 1
]

_COMPILED = [(name, re.compile(pat)) for name, pat in RULES]

# 배지로 내보내는 최대 개수. 실측 중위 2개·최대 5개라, 3개면 대부분의 줄이 전부
# 보이고 많아야 한 줄이 '+2' 를 단다.
MAX_BADGES = 3


def extract(memo: str | None) -> list[str]:
    """메모 한 줄 → 태그 목록. **우선순위 순서**로 돌려준다.

    못 알아보면 빈 목록이다. 억지로 하나 만들어 내지 않는다 — 50건 중 2건은
    가격에 걸리는 말이 아예 없었고, 그건 사실 그대로 비는 것이 맞다.
    """
    if not memo:
        return []
    return [name for name, rx in _COMPILED if rx.search(memo)]


# 사전에 없는 낱말을 셀 때 제외하는 말. 세면 많이 나오지만 규칙으로 만들 가치가
# 없다 — 안 빼면 '좋아요'·'완죤' 이 상위를 채워 정작 볼 것이 안 보인다.
STOP = {
    "좋아요", "있어요", "합니다", "입니다", "드실", "쏙드는", "맘에", "완죤",
    "완전", "강추", "최고", "최상", "추천", "하시면", "같아요", "언제든",
    "언제든지", "가능", "가능합니다", "주세요", "보시면", "그대로",
}

# 낱말 후보. 한글 2자 이상, 또는 'P3000' 같은 영문+숫자.
WORD = re.compile(r"[가-힣]{2,}|[A-Za-z]{1,3}\d{3,5}")


def tally(memos: list[str]) -> dict:
    """메모 목록에 사전을 재 본다. 화면과 `scripts/memo_report.py` 가 같이 쓴다.

    두 곳에서 따로 세면 화면과 보고서가 다른 숫자를 말하게 된다. 한 함수로 둔다.
    """
    counts = {name: 0 for name, _ in RULES}
    untagged: list[str] = []
    for m in memos:
        got = extract(m)
        for name in got:
            counts[name] += 1
        if not got:
            untagged.append(m)

    # 아직 아무 규칙에도 안 걸리는 낱말. 규칙을 늘릴 거리가 여기 있다.
    free: dict[str, int] = {}
    for m in memos:
        for w in set(WORD.findall(m)):
            if w in STOP or extract(w):
                continue
            free[w] = free.get(w, 0) + 1
    unknown = sorted(free.items(), key=lambda kv: (-kv[1], kv[0]))

    return {
        "counts": counts,
        "n_memos": len(memos),
        "untagged": untagged,
        "unknown": [{"word": w, "n": n} for w, n in unknown if n >= 2][:30],
    }


def merge(memos: list[str | None]) -> list[str]:
    """한 줄(유닛)에 접힌 여러 매물의 메모를 합친다.

    순위표의 한 줄은 호가 하나가 아니라 접힌 단위(단지·동·평형·층)다. 같은 층대에
    매물이 여럿이면 메모도 여럿이다. **합집합**을 쓰되 우선순위 순서는 지킨다 —
    한 건만 '급매' 라고 적었어도 그 줄에는 급매가 있다는 뜻이기 때문이다.
    """
    found = set()
    for m in memos:
        found.update(extract(m))
    return [name for name, _ in RULES if name in found]
