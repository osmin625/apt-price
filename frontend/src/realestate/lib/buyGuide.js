/**
 * 집 구하기 — 단계별 할 일 목록과 그 안의 갈림길. 화면(`views/GuideView.jsx`)은 이것을 그리기만 한다.
 *
 * ## 무엇을 바탕으로 했나
 *
 * - 사기 전 여섯 단계(내 상황 → 예산 → 매물 유형 → 입지 → 매물 → 임장)와 토지거래허가·계약 전 확인은
 *   사용자의 매수 준비 노트(2026-11-14 요청 때 받은 노션 페이지)의 순서를 따랐다. 노트에 있던 특정 회사의
 *   대출 조건·후보 매물·동호수는 **옮기지 않았다** — 정적 사이트로 공개되고, 남에게는 쓸모가 없다.
 *   거기서 나온 일반적인 교훈(거치 기간이 끝나면 월 상환이 몇 배로 뛴다, 회사 지원 이자는 소득으로 과세될
 *   수 있다, 소형 평형이 많은 재건축은 분담금이 커진다)만 남겼다.
 * - 이사 시기별 목록(한 달 전 → 당일)은 이사업체가 공개한 체크리스트의 시기 구분을 따랐다. 그 글은 **세입자
 *   기준**이라 매수자에게 안 맞는 것(확정일자, 전세권 설정 서류)은 뺐고, 전출 신고는 뺐다 — 전입신고를 하면
 *   전출이 같이 처리된다. 업체 홍보성 수치(보상 한도·혜택 금액)도 옮기지 않았다.
 * - 두 출처 모두 비어 있던 **계약·잔금·등기·입주 후**는 보강했다.
 *
 * ## 갈림길 — 고르면 그 뒤 흐름이 바뀐다 (2026-11-15 요청)
 *
 * 처음에는 '전월세에 살면'·'재건축' 같은 조건을 항목 옆 배지로만 달았다. 그러면 읽는 사람이 배지마다
 * 자기에게 해당하는지 따져야 하고, 해당하지 않는 항목도 다 남아 진척 수를 부풀렸다. 그래서 **정해야 하는
 * 것**을 목록 안의 갈림길(`kind: 'decision'`)로 두고, 고른 답에 따라 그 뒤 항목·단계가 나타나거나 사라지게
 * 했다. 갈림길은 흐름에서 그 결정을 내리는 자리에 둔다 — 지금 사는 집(내 상황)이 이사 단계의 '보증금
 * 돌려받기' 를 켜는 것처럼, 앞에서 고른 답이 멀리 뒤까지 미친다.
 *
 * - 고른 답의 `info` 는 '알아 둘 것' 으로 그 자리에 펼친다. 분석 탭의 '설명은 ⓘ 로 접는다' 와 어긋나
 *   보이지만, 여기서는 그것이 **본문**이다 — 사용자가 흐름을 따라 '이 선택이면 무엇을 알아야 하나' 를
 *   보자고 했다. 대신 한 줄씩만 펼치고, 긴 설명은 그 줄의 ⓘ(`{ t, d }` 의 d)로 접는다.
 * - 고르기 전에는 각 답의 `sub` 한 줄이 '어떤 경우에 맞나' 를 말한다. 견줄 것이 많으면 갈림길 `hint` 에.
 * - 답을 고르지 않은 갈림길에 매인 항목은 **보이지 않는다.** 아직 해당하는지 모르는 할 일을 미리 늘어놓으면
 *   처음의 배지 문제로 돌아간다. 갈림길 자체가 할 일 하나로 진척에 들어간다.
 * - `when: { 갈림길: [답…] }` — 열쇠가 여럿이면 모두 맞아야 하고, 한 열쇠 안에서는 하나라도 맞으면 된다.
 *   여럿 고르는 갈림길(`multi`)은 고른 답 중 하나라도 들어 있으면 맞다. 갈림길에도 `when` 을 단다
 *   (갈아타기 순서는 '지금 집이 내 집' 일 때만 묻는다).
 * - 갈림길 id 도 항목 id 처럼 저장 열쇠다. 답 값(`v`)을 바꾸면 그 답을 고른 기록이 사라진다.
 *
 * ## 무엇을 적지 않았나 — 바뀌는 숫자
 *
 * LTV·DSR 한도, 취득세율, 중개보수 요율, 정책 대출 금리·자격, 토지거래허가구역·규제지역 목록은 **적지
 * 않는다.** 정책 발표 하나로 바뀌고, 바뀌는 순간 이 목록만 그날에 멈춘다(CLAUDE.md '화면 문구에는 시간이
 * 지나도 맞는 것만'). 대신 '어디서 확인하나' 를 적는다. 남긴 숫자는 법이 정한 기한(거래신고 30일, 취득세·
 * 이전등기 60일, 전입신고 14일, 재산세 기준일 6월 1일, 허가 처리 15일, 묵시적 갱신 해지 3개월)과 사용자
 * 노트의 경험칙(세대수 500, 인구의 0.5%, 월급의 30%)뿐이다. 앞의 것도 법이 바뀌면 바뀌므로 화면 머리
 * ⓘ 에 그렇게 적었다.
 *
 * ## 모양
 *
 * - 항목: `{ id, t: 한 줄, d?: [ⓘ 에 접을 설명], go?: [탭 id, 탭 이름], when? }`
 * - 갈림길: `{ kind: 'decision', id, short: 요약 칩 이름, q: 묻는 말, multi?, hint?, when?,
 *   options: [{ v, label, sub?, only?, info?: [문장 | { t, d }] }] }`. `only` 는 여럿 고르는 갈림길에서
 *   다른 답과 함께 고를 수 없는 답이다('대출 없이' 와 '정책 대출' 을 같이 고르면 둘 다 틀린 흐름이 나온다).
 * - 단계: `{ id, title, hint?, when?, items }`. 단계 id 는 카드 링크(`#buy-guide/<id>`)도 된다.
 */

