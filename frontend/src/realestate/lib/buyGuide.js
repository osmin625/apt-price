/** 고른 답(`{ 갈림길: [답…] }`)에 비춰 `when` 이 맞나. 아직 안 고른 갈림길에 매인 것은 맞지 않는다. */
export function applies(when, choices) {
  if (!when) return true
  return Object.entries(when).every(([k, vs]) => (choices[k] || []).some((v) => vs.includes(v)))
}

const allEntries = () =>
  PHASES.flatMap((p) => p.steps.flatMap((s) => s.items.map((it) => ({ it, step: s, phase: p }))))

/** 모든 항목 id — 저장된 체크 중 사라진 항목을 거를 때 쓴다. */
export const ALL_ITEM_IDS = allEntries().filter((e) => e.it.kind !== 'decision').map((e) => e.it.id)

/** 갈림길 id → { 답 값 집합 } — 저장된 답 중 사라진 것을 거를 때 쓴다. */
export const DECISION_VALUES = Object.fromEntries(
  allEntries()
    .filter((e) => e.it.kind === 'decision')
    .map((e) => [e.it.id, new Set(e.it.options.map((o) => o.v))]),
)

/** 흐름 순서대로의 갈림길과 그것이 놓인 시기·단계 — 머리의 '내 선택' 줄이 쓴다. */
export const DECISIONS = allEntries()
  .filter((e) => e.it.kind === 'decision')
  .map((e) => ({ ...e.it, stepWhen: e.step.when, phaseWhen: e.phase.when }))
